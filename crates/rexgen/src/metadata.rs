use anyhow::{Error, Result};
use sha2::{Digest, Sha256};

pub const LOCK_SCHEMA_VERSION: u32 = 1;

#[derive(Debug, serde::Serialize, serde::Deserialize)]
pub struct SchemaLock {
    pub schema_version: u32,
    pub api_revision: u32,
    pub rex_version: String,
    pub server_commit: String,
    pub server_dirty: bool,
    pub schema_sha256: String,
}

#[derive(Debug, serde::Deserialize)]
pub struct ServerVersion {
    api_revision: u32,
    rex_version: String,
    commit: String,
    dirty: bool,
}

impl SchemaLock {
    pub fn new(schema_version: u32, server_version: ServerVersion, spec_bytes: &Vec<u8>) -> Self {
        let schema_sha256 = hex::encode(Sha256::digest(&spec_bytes));
        SchemaLock {
            schema_version,
            api_revision: server_version.api_revision,
            rex_version: server_version.rex_version,
            server_commit: server_version.commit,
            server_dirty: server_version.dirty,
            schema_sha256,
        }
    }
    pub fn generate_header(&self) -> String {
        format!(
            "// @generated by rexgen. DO NOT EDIT.\n\
             // API revision: {}\n\
             // Schema SHA-256: {}\n\n",
            self.api_revision, self.schema_sha256,
        )
    }

    pub fn verify_integrity(&self, bytes: &Vec<u8>) -> Result<()> {
        let hash = hex::encode(Sha256::digest(bytes));

        if hash != self.schema_sha256 {
            anyhow::bail!(
                "schema hash mismatch: lock expects {}, schema is {}",
                self.schema_sha256,
                hash
            );
        }
        Ok(())
    }
}

impl TryFrom<Vec<u8>> for SchemaLock {
    type Error = Error;
    fn try_from(value: Vec<u8>) -> Result<Self, Self::Error> {
        Ok(serde_json::from_slice(&value)?)
    }
}
